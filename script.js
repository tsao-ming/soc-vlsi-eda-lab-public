let currentLanguage = "zh";
let siteImages = null;

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[character]);
}

function safeImagePath(value) {
  if (typeof value !== "string" || !/^assets\/[A-Za-z0-9._/-]+$/.test(value)) return "";
  if (value.split("/").includes("..")) return "";
  return value;
}

function renderMembers() {
  const membersGrid = document.querySelector("#members-grid");
  if (!membersGrid) return;
  const entries = Array.isArray(siteImages?.members) && siteImages.members.length === members.length
    ? siteImages.members
    : members.map((name, index) => ({ id: `member-${String(index + 1).padStart(2, "0")}`, name, image: defaultMemberImage(index) }));
  membersGrid.innerHTML = entries
    .map((entry, index) => {
      const name = typeof entry.name === "string" ? entry.name : members[index];
      const mottoIndex = members.indexOf(name);
      const motto = translations[currentLanguage].memberMottos[mottoIndex >= 0 ? mottoIndex : index] || "";
      const image = safeImagePath(entry.image) || defaultMemberImage(index);
      return `
      <article class="member-card">
        <div class="member-photo">
          <img class="member-portrait" data-member-image="${escapeHtml(entry.id || `member-${String(index + 1).padStart(2, "0")}`)}" src="${escapeHtml(image)}" alt="${escapeHtml(name)}${escapeHtml(translations[currentLanguage].memberPhotoAlt)}" loading="lazy" />
        </div>
        <div class="member-info">
          <h3 class="member-name">${escapeHtml(name)}</h3>
          <p class="member-role">${escapeHtml(translations[currentLanguage].memberRole)}</p>
          <p class="member-motto">${escapeHtml(motto)}</p>
        </div>
      </article>`;
    })
    .join("");
}

function renderImageSlots() {
  for (const [slot, languageKey] of [["hero", "heroPhotoAlt"], ["professor", "professorPhotoAlt"]]) {
    const media = document.querySelector(`[data-image-slot="${slot}"]`);
    const record = siteImages?.[slot];
    const source = safeImagePath(record?.image);
    if (!media) continue;
    if (media instanceof HTMLVideoElement) {
      if (source) media.poster = source;
      media.setAttribute("aria-label", typeof record?.alt?.[currentLanguage] === "string"
        ? record.alt[currentLanguage]
        : translations[currentLanguage].heroVideoLabel);
      continue;
    }
    if (source) media.src = source;
    if (typeof record?.alt?.[currentLanguage] === "string") media.alt = record.alt[currentLanguage];
    else media.alt = translations[currentLanguage][languageKey];
  }
  renderMembers();
  renderGallery();
}

function renderGallery() {
  const grid = document.getElementById("gallery-grid");
  const empty = document.getElementById("gallery-empty");
  if (!grid || !empty) return;
  const records = Array.isArray(siteImages?.gallery) ? siteImages.gallery : [];
  empty.hidden = records.length > 0;
  grid.innerHTML = records.map((record) => {
    const image = safeImagePath(record.image);
    if (!image) return "";
    const title = record.title?.[currentLanguage] || record.title?.zh || record.title?.en || "";
    const description = record.description?.[currentLanguage] || record.description?.zh || record.description?.en || "";
    const date = typeof record.date === "string" ? record.date : "";
    return `<article class="gallery-card"><img src="${escapeHtml(image)}" alt="${escapeHtml(title)}" loading="lazy" /><div class="gallery-card-copy">${date ? `<time datetime="${escapeHtml(date)}">${escapeHtml(date)}</time>` : ""}${title ? `<h3>${escapeHtml(title)}</h3>` : ""}${description ? `<p>${escapeHtml(description)}</p>` : ""}</div></article>`;
  }).join("");
}

async function loadSiteImages() {
  try {
    const response = await fetch("site-images.json", { cache: "no-store" });
    if (!response.ok) throw new Error("Image list unavailable");
    const data = await response.json();
    if (data?.version !== 1 || !Array.isArray(data.members) || !Array.isArray(data.gallery)) throw new Error("Image list invalid");
    siteImages = data;
  } catch {
    siteImages = null;
  }
  renderImageSlots();
}

function renderPublications() {
  const data = window.publicationData;
  if (!data) return;
  const renderGroup = (records, targetId, countId) => {
    const target = document.getElementById(targetId);
    const count = document.getElementById(countId);
    if (count) count.textContent = String(records.length);
    if (!target) return;
    target.innerHTML = records.map(([authors, title, venue, year]) => `
      <li class="publication-item">
        <span class="paper-year">${escapeHtml(year)}</span>
        <div><h3>${escapeHtml(title)}</h3><p>${escapeHtml(authors)}</p><p class="paper-venue">${escapeHtml(venue)}</p></div>
      </li>`).join("");
  };
  renderGroup(data.journals, "journal-papers", "journal-count");
  renderGroup(data.conferences, "conference-papers", "conference-count");
}

function applyLanguage(language) {
  currentLanguage = language === "en" ? "en" : "zh";
  const dictionary = translations[currentLanguage];
  document.documentElement.lang = currentLanguage === "en" ? "en" : "zh-Hant";
  document.body.dataset.language = currentLanguage;
  const pageType = document.body.dataset.page;
  const isCoursePage = pageType === "course";
  const isCareerPage = pageType === "career";
  document.title = isCoursePage ? dictionary.coursePageTitle : isCareerPage ? dictionary.careerPageTitle : dictionary.pageTitle;

  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = isCoursePage ? dictionary.coursePageDescription : isCareerPage ? dictionary.careerPageDescription : dictionary.pageDescription;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAria];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAlt];
    if (value !== undefined) element.setAttribute("alt", value);
  });

  const toggle = document.getElementById("language-toggle");
  if (toggle) {
    toggle.textContent = currentLanguage === "zh" ? "EN" : "中文";
    toggle.setAttribute("aria-label", dictionary.toggleLabel);
  }
  renderImageSlots();
}

